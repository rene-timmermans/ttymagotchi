func portraitFor(p Tamagotchi) []string {
	level := growthIndex(p.Stage)
	if p.compactArt || level < 4 {
		return strings.Split(petArtwork[p.Species][max(1, level)-1], "\n")
	}
	variant, grow := 0, 0
	if level >= 6 {
		variant = 1
		grow = level - 6
	} else {
		grow = level - 4
	}
	if level == 9 {
		variant = 2
		grow = 0
	}
	source := strings.Split(petPortraits[p.Species][variant], "\n")
	rows := make([]string, 0, len(source)+grow)
	for _, line := range source {
		if line == "{grow}" {
			for i := 0; i < grow; i++ {
				rows = append(rows, rows[len(rows)-1])
			}
		} else {
			rows = append(rows, line)
		}
	}
	return rows
}
